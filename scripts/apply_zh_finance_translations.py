def quote_po(value: str) -> str:
	return value.replace("\\", "\\\\").replace('"', '\\"')


def main() -> None:
	po_path = Path(__file__).parents[1] / "erpnext" / "locale" / "zh.po"
	lines = po_path.read_text().splitlines(keepends=True)
	applied = set()

	for index, line in enumerate(lines[:-1]):
		if not line.startswith('msgid "') or not line.endswith('"\n'):
			continue
		msgid = line[7:-2].replace('\\"', '"').replace('\\\\', '\\')
		translation = TRANSLATIONS.get(msgid)
		if translation is None or not lines[index + 1].startswith('msgstr "'):
			continue
		expected = f'msgstr "{quote_po(translation)}"\n'
		if lines[index + 1] == 'msgstr ""\n':
			lines[index + 1] = expected
		applied.add(msgid)

	missing = sorted(set(TRANSLATIONS) - applied)
	if missing:
		lines.append("\n# Chinese finance localization overrides\n")
		for msgid in missing:
			lines.append(f'msgid "{quote_po(msgid)}"\n')
			lines.append(f'msgstr "{quote_po(TRANSLATIONS[msgid])}"\n\n')
		applied.add(msgid)

	po_path.write_text("".join(lines))
	print(f"Applied {len(applied)} reviewed finance translations")


if __name__ == "__main__":
	main()
